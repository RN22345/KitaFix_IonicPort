// The three roles in the system
export type Role = 'admin' | 'technician' | 'customer';

// Everything a role can be allowed to do (shown as checks on the Account profile page)
export const ALL_PERMISSIONS: string[] = [
  'Manage accounts',
  'Manage roles',
  'Schedule appointments',
  'Track repair status',
  'Manage technicians',
  'Register devices',
  'View service history',
  'View reports',
];

// Turns a saved gender value into the text shown on screen
export const GENDER_NAMES: Record<string, string> = {
  male: 'Male',
  female: 'Female',
  other: 'Other',
  'prefer-not': 'Prefer not to say',
};

// One user account (customer, technician or admin)
// TODO: later this can be built from the types generated by Supabase
export interface Account {
  id: string;
  accountNo?: string;
  firstName: string;
  lastName: string;
  email: string;
  contactNo: string;
  address?: string; // added: the FSD profile has an address
  birthday: string; // YYYY-MM-DD
  gender: string;
  profilePictureUrl?: string;
  role: Role;
  isActive: boolean; // added: false = the account can't log in (Accounts list status)
  joinedDate: string; // added: YYYY-MM-DD, shown on the Account profile page
}

// A role and what it is allowed to do
export interface RoleInfo {
  key: Role;
  name: string;
  description: string;
  permissions: string[];
}